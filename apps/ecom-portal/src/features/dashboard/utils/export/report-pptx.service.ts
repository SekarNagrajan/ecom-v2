export interface BuildReportPptxOptions {
  formatGeneratedAt: (isoUtc: string) => string;
  chartTokens: ChartTokens;
  formatNumber: (value: number) => string;
  formatCurrency: (value: number) => string;
}

export interface ReportPptxDownloadResult {
  filename: string;
  missingChartCount: number;
}

const SUBJECT = "E-com Dashboard Report";
const SLIDE_CX = 9144000;
const SLIDE_CY = 5143500;
