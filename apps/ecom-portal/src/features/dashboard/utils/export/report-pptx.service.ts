export async function downloadReportPptx(
  report: DashboardReport,
  options: BuildReportPptxOptions,
): Promise<ReportPptxDownloadResult> {
  const filename = buildReportFilename(report, "pptx");
  try {
    const mod = await import("pptxgenjs");
    return await downloadWithPptxgenjs(mod.default, report, options, filename);
  } catch {
    return downloadWithFflate(report, options, filename);
  }
}

async function downloadWithPptxgenjs(
  PptxGenJS: typeof import("pptxgenjs").default,
  report: DashboardReport,
  options: BuildReportPptxOptions,
  filename: string,
): Promise<ReportPptxDownloadResult> {
  const pptx = new PptxGenJS();
  pptx.defineLayout({ name: "LAYOUT_16x9", width: 10, height: 5.625 });
  pptx.layout = "LAYOUT_16x9";
  pptx.author = report.generatedBy;
  pptx.title = report.title;
  pptx.subject = SUBJECT;
  pptx.company = SUBJECT;

  const chartContext = toChartContext(options);
  let missingChartCount = 0;
  const filterLines =
    report.appliedFilters.length > 0
      ? report.appliedFilters.map((f) => `${f.label}: ${f.value}`).join("\n")
      : "—";

  addTextSlide(pptx, report.title, [
    report.tenantName,
    `Generated by ${report.generatedBy}`,
    options.formatGeneratedAt(report.generatedAt),
    "",
    "Applied Filters",
    filterLines,
  ]);

  iterateReportSections(report, {
    onKpi: (section) => {
      addTextSlide(
        pptx,
        section.title,
        section.items.map((i) => `${i.label}: ${displayReportCell(i.value)}`),
      );
    },
    onChart: (section) => {
      const slide = pptx.addSlide();
      slide.addText(section.title, {
        x: 0.5, y: 0.28, w: 9, h: 0.4, fontSize: 18, bold: true, color: "111827", fontFace: "Arial",
      });
      const png = tryChartPng(section, chartContext);
      if (png) {
        slide.addImage({ data: png, x: 0.5, y: 0.9, w: 9, h: 4.2 });
      } else {
        missingChartCount += 1;
        slide.addText("Chart unavailable", {
          x: 0.5, y: 0.9, w: 9, h: 4.2, fontSize: 14, color: "6B7280",
          align: "center", valign: "middle", fontFace: "Arial",
        });
      }
    },
    onTable: (section) => {
      for (const chunk of chunkTableBodyRows(section.rows, TABLE_ROWS_PER_SLIDE)) {
        addTextSlide(pptx, section.title, tableLines(section, chunk));
      }
    },
  });

  await pptx.writeFile({ fileName: filename });
  return { filename, missingChartCount };
}

function addTextSlide(
  pptx: InstanceType<typeof import("pptxgenjs").default>,
  title: string,
  lines: string[],
): void {
  const slide = pptx.addSlide();
  slide.addText(`${title}\n\n${lines.join("\n")}`, {
    x: 0.5, y: 0.28, w: 9, h: 5, fontSize: 14, color: "111827", fontFace: "Arial", valign: "top",
  });
}

async function downloadWithFflate(
  report: DashboardReport,
  options: BuildReportPptxOptions,
  filename: string,
): Promise<ReportPptxDownloadResult> {
  const { zipSync, strToU8 } = await import("fflate");
  const chartContext = toChartContext(options);
  const slides: Array<{ xml: string; image?: Uint8Array }> = [];
  let missingChartCount = 0;
  let imageSeq = 0;

  const filterText =
    report.appliedFilters.length > 0
      ? report.appliedFilters.map((f) => `${f.label}: ${f.value}`).join("\n")
      : "—";
  slides.push({
    xml: textSlideXml(report.title, [
      report.tenantName,
      `Generated by ${report.generatedBy}`,
      options.formatGeneratedAt(report.generatedAt),
      "",
      "Applied Filters",
      filterText,
    ]),
  });

  iterateReportSections(report, {
    onKpi: (section: DashboardReportKpiSection) => {
      slides.push({
        xml: textSlideXml(
          section.title,
          section.items.map((i) => `${i.label}: ${displayReportCell(i.value)}`),
        ),
      });
    },
    onChart: (section: DashboardReportChartSection) => {
      const png = tryChartPng(section, chartContext);
      if (png) {
        imageSeq += 1;
        slides.push({
          xml: imageSlideXml(section.title, `rIdImg${imageSeq}`),
          image: dataUrlToBytes(png),
        });
      } else {
        missingChartCount += 1;
        slides.push({ xml: textSlideXml(section.title, ["Chart unavailable"]) });
      }
    },
    onTable: (section: DashboardReportTableSection) => {
      for (const chunk of chunkTableBodyRows(section.rows, TABLE_ROWS_PER_SLIDE)) {
        slides.push({ xml: textSlideXml(section.title, tableLines(section, chunk)) });
      }
    },
  });

  const files: Record<string, Uint8Array> = {
    "[Content_Types].xml": strToU8(contentTypesXml(slides)),
    "_rels/.rels": strToU8(ROOT_RELS),
    "docProps/core.xml": strToU8(coreXml(report)),
    "docProps/app.xml": strToU8(APP_XML),
    "ppt/presentation.xml": strToU8(presentationXml(slides.length)),
    "ppt/_rels/presentation.xml.rels": strToU8(presentationRels(slides.length)),
    "ppt/slideMasters/slideMaster1.xml": strToU8(SLIDE_MASTER),
    "ppt/slideMasters/_rels/slideMaster1.xml.rels": strToU8(MASTER_RELS),
    "ppt/slideLayouts/slideLayout1.xml": strToU8(SLIDE_LAYOUT),
    "ppt/slideLayouts/_rels/slideLayout1.xml.rels": strToU8(LAYOUT_RELS),
    "ppt/theme/theme1.xml": strToU8(THEME_XML),
  };

  let mediaIndex = 0;
  slides.forEach((slide, i) => {
    const n = i + 1;
    files[`ppt/slides/slide${n}.xml`] = strToU8(slide.xml);
    if (slide.image) {
      mediaIndex += 1;
      files[`ppt/media/image${mediaIndex}.png`] = slide.image;
      files[`ppt/slides/_rels/slide${n}.xml.rels`] = strToU8(
        slideRels(`rIdImg${mediaIndex}`, mediaIndex),
      );
    } else {
      files[`ppt/slides/_rels/slide${n}.xml.rels`] = strToU8(SLIDE_RELS);
    }
  });

  const url = URL.createObjectURL(
    new Blob([zipSync(files)], {
      type: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    }),
  );
  downloadObjectUrl(url, filename);
  URL.revokeObjectURL(url);
  return { filename, missingChartCount };
}

function tableLines(
  section: DashboardReportTableSection,
  chunk: Record<string, string | number | null>[],
): string[] {
  const header = section.columns.map((c) => c.label).join(" | ");
  const body = chunk.map((row) =>
    section.columns.map((col) => displayReportCell(row[col.key])).join(" | "),
  );
  return section.footnote ? [header, ...body, "", section.footnote] : [header, ...body];
}

function toChartContext(options: BuildReportPptxOptions): ReportChartContext {
  return {
    tokens: options.chartTokens,
    formatNumber: options.formatNumber,
    formatCurrency: options.formatCurrency,
  };
}

function tryChartPng(
  section: DashboardReportChartSection,
  ctx: ReportChartContext,
): string | null {
  try {
    return renderChartSectionToPng(section, ctx);
  } catch (error) {
    console.error("[dashboard-export] chart render failed", section.id, error);
    return null;
  }
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function dataUrlToBytes(dataUrl: string): Uint8Array {
  const base64 = dataUrl.includes(",") ? dataUrl.split(",")[1]! : dataUrl;
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

function paras(lines: string[]): string {
  return lines
    .map((line) => `<a:p><a:r><a:rPr lang="en-US" sz="1400"/><a:t>${escapeXml(line) || " "}</a:t></a:r></a:p>`)
    .join("");
}

