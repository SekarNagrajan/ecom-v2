function toDateKey(iso: string): string {
  return iso.slice(0, 10);
}

/** Filter mock rows by DO date (inclusive YYYY-MM-DD). */
export function filterMockDeliveryOrders(
  rows: readonly DOSummaryRow[],
  filters: { fromDate?: string; toDate?: string },
): DOSummaryRow[] {
  const from = filters.fromDate?.trim();
  const to = filters.toDate?.trim();

  return rows.filter((row) => {
    const key = toDateKey(row.delorddate);
    if (from && key < from) return false;
    if (to && key > to) return false;
    return true;
  });
}

