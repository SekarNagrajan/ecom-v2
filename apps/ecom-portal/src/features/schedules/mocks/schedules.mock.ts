function daysBefore(isoDateTime: string, days: number, hour = "18:00"): string {
  const [datePart] = isoDateTime.split(" ");
  const date = new Date(`${datePart}T12:00:00Z`);
  date.setUTCDate(date.getUTCDate() - days);
  const y = date.getUTCFullYear();
  const m = String(date.getUTCMonth() + 1).padStart(2, "0");
  const d = String(date.getUTCDate()).padStart(2, "0");
  return `${y}-${m}-${d} ${hour}`;
}

function defaultDeadlines(etd: string): CutOffDeadlines {
  return {
    containerGateIn: daysBefore(etd, 2, "22:00"),
    siDocClosing: daysBefore(etd, 2, "16:00"),
    vgmClosing: daysBefore(etd, 2, "18:00"),
  };
}

function buildSchedule(seed: ScheduleSeed): ScheduleItem {
  const legs: RouteLeg[] = seed.legs.map((leg, index) => ({
    id: `LEG-${seed.id}-${index + 1}`,
    legType: leg.legType,
    vesselName: leg.vessel.name,
    vesselCode: leg.vessel.code,
    voyage: leg.vessel.voyage,
    bound: leg.vessel.bound,
    serviceName: leg.serviceName,
    serviceCode: leg.serviceCode,
    polPortId: leg.pol.id,
    polPortName: leg.pol.shortName,
    podPortId: leg.pod.id,
    podPortName: leg.pod.shortName,
    etd: leg.etd,
    eta: leg.eta,
    terminal: leg.pol.terminal,
  }));

  const isDirect = legs.length <= 1;
  return {
    id: seed.id,
    serviceCode: seed.serviceCode,
    serviceName: seed.serviceName,
    isDefaultRoute: seed.isDefaultRoute ?? false,
    polPortId: seed.pol.id,
    polPortName: seed.pol.name,
    podPortId: seed.pod.id,
    podPortName: seed.pod.name,
    polTerminal: seed.pol.terminal,
    podTerminal: seed.pod.terminal,
    etd: seed.etd,
    eta: seed.eta,
    transitTimeDays: seed.transitTimeDays,
    isDirect,
    transshipmentCount: Math.max(0, legs.length - 1),
    isMultimodal: seed.isMultimodal ?? false,
    vesselName: seed.vessel.name,
    vesselCode: seed.vessel.code,
    voyage: seed.vessel.voyage,
    bound: seed.vessel.bound,
    deadlines: seed.deadlines,
    distanceKm: seed.distanceKm,
    bookingAllowed: seed.bookingAllowed ?? true,
    legs,
  };
}

function directLeg(
  seed: Omit<ScheduleSeed, "legs" | "deadlines"> & {
    deadlines?: CutOffDeadlines;
    legType?: RouteLeg["legType"];
  },
): ScheduleSeed {
  return {
    ...seed,
    deadlines: seed.deadlines ?? defaultDeadlines(seed.etd),
    legs: [
      {
        legType: seed.legType ?? "Mainline",
        vessel: seed.vessel,
        serviceCode: seed.serviceCode,
        serviceName: seed.serviceName,
        pol: seed.pol,
        pod: seed.pod,
        etd: seed.etd,
        eta: seed.eta,
      },
    ],
  };
}

